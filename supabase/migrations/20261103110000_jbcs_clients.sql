-- Client directory for the public Feedback page and private website dashboard.
-- Public visitors must only see published client records through a server-side API.
create table if not exists public.jbcs_clients (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  logo_url text not null,
  website_url text,
  description text,
  is_published boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint jbcs_clients_name_not_blank check (length(trim(name)) > 0),
  constraint jbcs_clients_logo_url_not_blank check (length(trim(logo_url)) > 0),
  constraint jbcs_clients_website_url_format check (website_url is null or website_url ~* '^https?://')
);

create index if not exists jbcs_clients_published_sort_idx
  on public.jbcs_clients (is_published, sort_order, name);

alter table public.jbcs_clients enable row level security;
revoke all on public.jbcs_clients from anon, authenticated;
grant select, insert, update, delete on public.jbcs_clients to service_role;

comment on table public.jbcs_clients is
  'Client organizations displayed on the public Feedback page; managed by authorized website administrators.';
comment on column public.jbcs_clients.logo_url is
  'Publicly reachable image URL or URL generated by the website media upload flow.';
comment on column public.jbcs_clients.website_url is
  'Optional official client website URL; must use http or https.';
